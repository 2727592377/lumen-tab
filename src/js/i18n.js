const dicts = { zh, en };
let lang = 'zh';

export function setLang(l) { lang = l === 'en' ? 'en' : 'zh'; document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN'; }
export function getLang() { return lang; }

export function t(key, vars) {
  const k = ALIAS[key] ?? key;
  let s = dicts[lang]?.[k] ?? dicts.zh[k] ?? k;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
  return s;
}

/** 给带 data-i18n 的元素批量上文字 */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((n) => { n.textContent = t(n.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((n) => n.setAttribute('placeholder', t(n.dataset.i18nPh)));
  root.querySelectorAll('[data-i18n-title]').forEach((n) => n.setAttribute('title', t(n.dataset.i18nTitle)));
}
